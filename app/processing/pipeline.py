import hashlib
import json
from pathlib import Path

from app.processing.invoice_extractor import InvoiceExtractor
from app.models.paddle_ocr import PaddleOCRModel
from app.processing.document_processor import DocumentProcessor
from app.processing.layout_analyzer import LayoutAnalyzer
from app.exporters.database_exporter import DatabaseExporter
from app.exporters.image_exporter import ImageExporter


class DocumentPipeline:
    SUPPORTED_FORMATS = {
        ".pdf", ".png", ".jpg", ".jpeg",
        ".bmp", ".tiff", ".tif", ".webp"
    }

    def __init__(self):
        self.input_dir = Path("input")
        self.input_dir.mkdir(parents=True, exist_ok=True)

        self.processor = DocumentProcessor()
        self.invoice_extractor = InvoiceExtractor()
        self.image_exporter = ImageExporter()

        self.ocr = PaddleOCRModel()
        self.layout_analyzer = LayoutAnalyzer()
        self.database = DatabaseExporter()

    def calculate_hash(self, file_path):
        sha256 = hashlib.sha256()
        with open(file_path, "rb") as file:
            for chunk in iter(lambda: file.read(8192), b""):
                sha256.update(chunk)
        return sha256.hexdigest()

    def get_input_images(self):
        return sorted(
            path for path in self.input_dir.iterdir()
            if path.is_file() and path.suffix.lower() in self.SUPPORTED_FORMATS
        )

    def _save_processed_page(self, document_path, file_hash, prepared_page):
        page_suffix = f"_page_{prepared_page.page_number:03d}"
        processed_filename = (
            f"{document_path.stem}_{file_hash[:8]}{page_suffix}_processed.png"
        )
        return self.image_exporter.save(prepared_page.image, processed_filename)

    def process_document(self, image_path):
        file_hash = self.calculate_hash(image_path)
        document_id = self.database.register_document(
            source_path=image_path,
            file_hash=file_hash,
            document_type="unknown",
            processing_status="uploaded",
        )

        try:
            print(f"\nProcessing: {image_path.name}")

            with self.database.connect() as db:
                status_row = db.execute(
                    """SELECT processing_status, ocr_engine
                       FROM document_processing
                       WHERE document_id = ?""",
                    (document_id,),
                ).fetchone()

            status = status_row[0] if status_row else None
            stored_engine = status_row[1] if status_row else None
            current_engine = self.ocr.MODEL_ID

            if status == "extraction_completed" and stored_engine == current_engine:
                print(f"Skipped: {image_path.name} (Already processed with {current_engine})")
                return "skipped"

            # A cache generated by the previous PaddleOCR text-recognition
            # engine must not be reused as PaddleOCR-VL 1.6 output.
            existing_result = self.database.get_ocr_results(document_id)
            if existing_result is not None and stored_engine == current_engine:
                print(f"Existing {current_engine} OCR found. Reusing stored layout.")
                if not existing_result[2]:
                    raise ValueError("Stored OCR layout is empty.")
                layout = json.loads(existing_result[2])
            else:
                if existing_result is not None:
                    print(
                        f"Refreshing OCR cache: {stored_engine or 'unknown'} "
                        f"-> {current_engine}."
                    )

                print("Preparing document pages...")
                prepared_pages = self.processor.process_pages(str(image_path))
                if not prepared_pages:
                    raise ValueError("No pages were produced for this document.")

                combined_layout = []
                combined_text = []
                total_detections = 0

                for prepared_page in prepared_pages:
                    processed_path = self._save_processed_page(
                        image_path, file_hash, prepared_page
                    )

                    print(
                        f"Running {current_engine} on page "
                        f"{prepared_page.page_number}/{len(prepared_pages)}..."
                    )
                    result = self.ocr.predict(str(processed_path))

                    print(f"Adapting page {prepared_page.page_number} layout...")
                    page_layout = self.layout_analyzer.analyze(result.results)

                    for line in page_layout:
                        combined_layout.append({
                            "text": line.get("text", ""),
                            "detection_ids": line.get("detection_ids", []),
                            "page_number": prepared_page.page_number,
                        })

                    combined_text.append(result.full_text)
                    total_detections += len(result.results)

                layout = combined_layout

                from app.models.ocr_result import DocumentOCRResult, OCRResult
                combined_result = DocumentOCRResult(
                    source_path=str(image_path.resolve()),
                    results=[OCRResult(text="") for _ in range(total_detections)],
                    full_text="\n".join(combined_text),
                    metadata={
                        "engine": current_engine,
                        "pipeline_version": "v1.6",
                        "page_count": len(prepared_pages),
                        "detection_count": total_detections,
                    },
                )
                self.database.save_ocr_results(
                    document_id=document_id,
                    result=combined_result,
                    layout=layout,
                )

                with self.database.connect() as db:
                    db.execute(
                        """UPDATE document_processing
                           SET ocr_engine = ?
                           WHERE document_id = ?""",
                        (current_engine, document_id),
                    )

                print("OCR blocks:", total_detections)
                print("Layout lines:", len(layout))

            print("Extracting invoice information...")
            invoice_data = self.invoice_extractor.extract(layout)

            print("\n========== EXTRACTED INVOICE ==========")
            for key, value in invoice_data.items():
                if key != "line_items":
                    print(f"{key}: {value}")

            print("\n========== LINE ITEMS ==========")
            for item in invoice_data.get("line_items", []):
                print(item)

            self.database.save_invoice_data(
                document_id=document_id,
                invoice_data=invoice_data,
            )

            print("\nDocument processed successfully.")
            return "processed"

        except Exception as error:
            self.database.update_processing_status(
                document_id=document_id,
                status="failed",
                error_message=str(error),
            )
            print(f"Failed: {image_path.name}")
            print("Reason:", error)
            return "failed"

    def run(self):
        documents = self.get_input_images()
        if not documents:
            print("No supported documents found in input/.")
            return

        print("\n========== DOCUFLOW AI ==========")
        print("OCR engine:", self.ocr.MODEL_ID)
        print("Documents found:", len(documents))

        processed = skipped = failed = 0
        try:
            self.ocr.load()
            for document_path in documents:
                result = self.process_document(document_path)
                if result == "processed":
                    processed += 1
                elif result == "skipped":
                    skipped += 1
                elif result == "failed":
                    failed += 1
        finally:
            self.ocr.unload()

        print("\n========== PROCESSING SUMMARY ==========")
        print("Processed:", processed)
        print("Skipped:", skipped)
        print("Failed:", failed)
        print("\nDatabase:", self.database.database_path.resolve())
